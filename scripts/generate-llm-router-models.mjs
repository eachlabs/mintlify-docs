function parseArgs(argv) {
  const args = { out: DEFAULT_OUT, openrouterUrl: DEFAULT_OPENROUTER_URL, baseUrl: DEFAULT_BASE_URL };
  for (let i = 0; i < argv.length; i++) {
    const arg = argv[i];
    switch (arg) {
      case "--catalog":
        args.catalog = argv[++i];
        break;
      case "--remote":
        args.remote = true;
        break;
      case "--base-url":
        args.baseUrl = argv[++i];
        break;
      case "--out":
        args.out = resolve(argv[++i]);
        break;
      case "--openrouter-url":
        args.openrouterUrl = argv[++i];
        break;
      default:
        fail(`unknown argument: ${arg}`);
    }
  }
  if (!args.catalog && !args.remote) {
    fail("pass --catalog <path to model-catalog.json> or --remote [--base-url <url>]");
  }
  if (args.catalog && args.remote) fail("--catalog and --remote are mutually exclusive");
  return args;
}

function fail(message) {
  console.error(`generate-llm-router-models: ${message}`);
  process.exit(1);
}

function loadLocalCatalog(path) {
  const decoded = JSON.parse(readFileSync(path, "utf8"));
  if (!Array.isArray(decoded.models)) fail(`catalog file has no models array: ${path}`);
  return decoded.models.map((m) => ({
    id: String(m.id ?? ""),
    status: String(m.status ?? ""),
    family: String(m.family ?? ""),
    targetModel: String(m.canonical_target_model ?? ""),
    title: String(m.title ?? ""),
  }));
}

async function fetchRemoteCatalog(baseUrl) {
  const response = await fetch(`${baseUrl.replace(/\/$/, "")}/graphql`, {
    method: "POST",
    headers: { "Content-Type": "application/json", Accept: "application/json" },
    body: JSON.stringify({ query: GRAPHQL_QUERY }),
  });
  if (!response.ok) fail(`GraphQL returned status ${response.status}`);
  const body = await response.json();
  if (body.errors) fail(`GraphQL returned errors: ${JSON.stringify(body.errors)}`);
  const catalog = body.data?.llmRouterModelCatalog;
  if (!Array.isArray(catalog?.models)) fail("GraphQL response missing llmRouterModelCatalog.models");
  return catalog.models.map((m) => ({
    id: String(m.id ?? ""),
    status: String(m.status ?? ""),
    family: String(m.family ?? ""),
    targetModel: String(m.canonicalTargetModel ?? ""),
    title: String(m.title ?? ""),
  }));
}

async function fetchOpenRouterPricing(url) {
  const response = await fetch(url, { headers: { Accept: "application/json" } });
  if (!response.ok) fail(`OpenRouter returned status ${response.status}`);
  const body = await response.json();
  if (!Array.isArray(body.data)) fail("OpenRouter response missing data array");
  const byId = new Map();
  for (const model of body.data) {
    if (!model?.id) continue;
    byId.set(String(model.id), {
      inputPerMillion: perMillion(model.pricing?.prompt),
      outputPerMillion: perMillion(model.pricing?.completion),
      contextLength: Number.isFinite(model.context_length) ? model.context_length : null,
    });
  }
  return byId;
}

function perMillion(raw) {
  const perToken = Number.parseFloat(raw);
  // OpenRouter uses negative prices (e.g. "-1") as a variable-pricing sentinel — treat as unpriced.
  return Number.isFinite(perToken) && perToken >= 0 ? perToken * 1_000_000 : null;
}

function loadOverrides() {
  if (!existsSync(OVERRIDES_PATH)) return new Map();
  const decoded = JSON.parse(readFileSync(OVERRIDES_PATH, "utf8"));
  const overrides = new Map();
  for (const [id, value] of Object.entries(decoded)) {
    if (id.startsWith("_") || typeof value !== "object" || value === null) continue;
    overrides.set(id, {
      inputPerMillion: numberOrNull(value.input_per_million),
      outputPerMillion: numberOrNull(value.output_per_million),
      contextLength: numberOrNull(value.context_length),
    });
  }
  return overrides;
}

function numberOrNull(value) {
  return Number.isFinite(value) ? value : null;
}

function formatPrice(perM) {
  if (perM === null) return "—";
  if (perM === 0) return "$0.00";
  if (perM >= 0.01) return `$${perM.toFixed(2)}`;
  return `$${perM.toFixed(4).replace(/\.?0+$/, "")}`;
}

function formatContext(length) {
  if (length === null) return "—";
  return String(length).replace(/\B(?=(\d{3})+(?!\d))/g, ",");
}

function escapeCell(value) {
  return value.replaceAll("|", "\\|");
}

function familyTitle(family) {
  if (FAMILY_TITLES[family]) return FAMILY_TITLES[family];
  return family
    .split(/[-_]/)
    .map((part) => part.charAt(0).toUpperCase() + part.slice(1))
    .join(" ");
}

function orderedFamilies(families) {
  const leading = FAMILY_ORDER.filter((family) => families.has(family));
  const rest = [...families]
    .filter((family) => !FAMILY_ORDER.includes(family))
    .sort((a, b) => {
      const at = familyTitle(a);
      const bt = familyTitle(b);
      if (at !== bt) return at < bt ? -1 : 1;
      return a < b ? -1 : 1;
    });
  return [...leading, ...rest];
}

function renderSections(models, pricingById, overrides) {
  const byFamily = new Map();
  for (const model of models) {
    if (!byFamily.has(model.family)) byFamily.set(model.family, []);
    byFamily.get(model.family).push(model);
  }

  const missingData = [];
  let fromOpenRouter = 0;
  let fromOverrides = 0;
  let knownUnpriced = 0;
  const sections = [];
  for (const family of orderedFamilies(new Set(byFamily.keys()))) {
    const rows = [...byFamily.get(family)].sort((a, b) => (a.id < b.id ? -1 : 1));
    const lines = [
      `## ${familyTitle(family)}`,
      "",
      "| Model ID | Name | Input | Output | Context |",
      "|-|-|-|-|-|",
    ];
    for (const model of rows) {
      const or = pricingById.get(model.targetModel) ?? pricingById.get(model.id) ?? null;
      const ov = overrides.get(model.id) ?? null;
      const inputPerMillion = or?.inputPerMillion ?? ov?.inputPerMillion ?? null;
      const outputPerMillion = or?.outputPerMillion ?? ov?.outputPerMillion ?? null;
      const contextLength = or?.contextLength ?? ov?.contextLength ?? null;
      if (or && (or.inputPerMillion !== null || or.outputPerMillion !== null)) fromOpenRouter++;
      else if (ov && (ov.inputPerMillion !== null || ov.outputPerMillion !== null)) fromOverrides++;
      else if (or || ov) knownUnpriced++;
      else missingData.push(model.id);
      const name = escapeCell(model.title || model.id);
      lines.push(
        `| \`${model.id}\` | ${name} | ${formatPrice(inputPerMillion)} | ${formatPrice(outputPerMillion)} | ${formatContext(contextLength)} |`
      );
    }
    sections.push(lines.join("\n"));
  }
  return { body: sections.join("\n\n"), fromOpenRouter, fromOverrides, knownUnpriced, missingData };
}

function preservedIntro(outPath) {
  if (!existsSync(outPath)) fail(`output file does not exist (frontmatter/intro must be preserved): ${outPath}`);
  const current = readFileSync(outPath, "utf8");
  const bannerIndex = current.indexOf("{/* Generated by scripts/generate-llm-router-models.mjs");
  if (bannerIndex !== -1) return current.slice(0, bannerIndex);
  const headingIndex = current.indexOf("\n## ");
  if (headingIndex !== -1) return current.slice(0, headingIndex + 1);
  fail(`could not locate the generated section (banner or first "## " heading) in ${outPath}`);
}

async function main() {
  const args = parseArgs(process.argv.slice(2));
  const catalog = args.catalog ? loadLocalCatalog(resolve(args.catalog)) : await fetchRemoteCatalog(args.baseUrl);
  const visible = catalog.filter((model) => model.id && model.status === "visible");
  if (visible.length === 0) fail("catalog produced zero visible models");

  const pricingById = await fetchOpenRouterPricing(args.openrouterUrl);
  if (pricingById.size < MIN_OPENROUTER_MODELS) {
    fail(
      `OpenRouter returned only ${pricingById.size} models (< ${MIN_OPENROUTER_MODELS}); ` +
        `refusing to emit a mostly-unpriced page from a truncated response`
    );
  }
  const overrides = loadOverrides();
  const { body, fromOpenRouter, fromOverrides, knownUnpriced, missingData } = renderSections(
    visible,
    pricingById,
    overrides
  );
  if (fromOpenRouter < visible.length * MIN_OPENROUTER_PRICED_RATIO) {
    fail(
      `only ${fromOpenRouter}/${visible.length} visible models got pricing from OpenRouter ` +
        `(< ${MIN_OPENROUTER_PRICED_RATIO * 100}%); refusing to emit a mostly-unpriced page`
    );
  }

  const output = `${preservedIntro(args.out)}${BANNER}\n\n${body}\n\n${FOOTER}\n`;
  writeFileSync(args.out, output);

  console.error(
    `generate-llm-router-models: wrote ${args.out} — ${visible.length} visible models ` +
      `(${fromOpenRouter} priced via OpenRouter, ${fromOverrides} priced via overrides, ` +
      `${knownUnpriced} known-unpriced (—), ${missingData.length} without any data source)`
  );
  if (missingData.length > 0) {
    console.error(
      `  models with no OpenRouter match and no entry in scripts/llm-router-models-overrides.json (rendered as —):`
    );
    for (const id of missingData) console.error(`    ${id}`);
  }
}

await main();
